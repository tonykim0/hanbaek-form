/**
 * 할 일의 모양 — 서버·클라이언트가 같이 보는 타입.
 *
 * ★lib/todos 와 갈라 둔 이유★ 조립(todosOf)은 저장소·세션을 끌어오고, 세션은
 * next/headers 를 쓴다 — 서버에서만 도는 것이다. 칸반은 'use client' 라, 거기서
 * lib/todos 를 타입 때문에 부르는 것만으로 그 사슬이 클라이언트 번들로 끌려 들어와
 * 빌드가 깨졌다(2026-08-24). 타입은 아무것도 끌어오지 않는 이 파일에 둔다.
 */
/**
 * 할 일이 속한 업무 — 화면에서는 「업무」라고 부른다(한백 확인 2026-08-24).
 * 코드·CLAUDE.md 는 계약·시공을 가르는 이 축을 국면이라 부르지만 그것은 안쪽 어휘다.
 */
export type TodoGroup = '계약' | '시공' | '지급' | '기성';

/**
 * 칸 순서 — ★일이 흘러가는 순서다★ (한백 확인 2026-08-24): 계약 → 시공 → 지급 → 기성.
 *
 * 처음에는 정산을 맨 위에 뒀다 — 배치 일이 1~2일 회전이라 급한 것을 앞에 두려던
 * 것이었다. 그런데 순서로 급함을 말하면 흐름을 잃는다: 사이드바도 현장 상세 탭도
 * 계약 → 시공 → 지급 → 기성이라, 할 일만 거꾸로면 같은 축을 두 방향으로 배우게 된다.
 * 급함은 자리가 아니라 칸 안 정렬(urgency)과 카드의 밀림 문구가 말한다.
 *
 * ★「정산」을 지급과 기성으로 갈랐다★ (한백 지시 2026-08-29). 돈의 방향이 반대다 —
 * 지급은 한백이 협력사에게 내려주는 것이고 기성은 운영사에게서 받는 것이다. 한 칸에
 * 섞이면 카드를 볼 때마다 어느 쪽 이야기인지 따져야 했고, 상대도 다르다. 이 이름은
 * 사이드바(협력사 지급관리 · 운영사 기성관리)와 현장 상세 탭이 쓰는 말과 같다.
 */
export const TODO_GROUPS = ['계약', '시공', '지급', '기성'] as const satisfies readonly TodoGroup[];

export interface TodoItem {
  id: string;
  /** 눌러서 갈 곳 — 조립이 정한다(현장 상세 · 거래명세서). 화면은 라우팅 규칙을 모른다 */
  href: string;
  name: string;
  what: string;
  group: TodoGroup;
  stalledDays: number;
  /**
   * 이 칸 안에서 무슨 일인가 — 계약 칸에 접수·검토·보완이 섞여 있어서 필요하다.
   * 현장 보드는 이것을 칸으로 갈랐는데 여기는 업무가 칸이라, 꼬리표로 갈린다.
   * 지급은 배치 일(세금계산서 발행·확정 누락), 기성은 걸린 자리(기성 수금·
   * 준공마감일 지정·정산 규칙 미지정)다.
   */
  kind: string;
  /**
   * 급함 — 칸을 넘어 견주는 잣대다.
   *
   * ★국면마다 급함의 근거가 다르다.★ 계약·시공은 정체일(며칠 멈춰 있나)이고, 정산은
   * 날짜(지급일이 얼마 남았나 · 얼마나 지났나)다. 정산 카드는 stalledDays 가 늘 0 이라
   * 정체로 재면 언제나 한가한 일로 보였다 — 확정 누락은 지급일이 지난 것이 곧 급함이다.
   * 그래서 국면과 무관하게 견줄 수 있는 한 숫자로 만든다: 클수록 급하다.
   */
  urgency: number;
  /** 급함을 사람 말로 — 카드에 그대로 적는다. 없으면 적을 것이 없다는 뜻이다 */
  urgencyLabel: string | null;
}
