-- 계약완료에 서 있는 현장의 공 차례를 한백으로 (한백 지시 2026-08-25)
--
-- 계약 확인 단추가 공 차례를 '시공사' 로 적고 있었다 — 「계약이 끝났으면 다음 손은 시공사」로
-- 봤는데, 계약완료 다음 일은 ★우리가 운영사에 계약서를 내는 것★이다. 그래서 협력사의 할 일
-- 목록에 「계약완료」가 떴다 — 표시만 있고 할 것이 없는 줄이다. 코드는 이제 단계로 판정한다
-- (lib/process.ts COURT_AFTER_STATUS, 계약완료 → 한백). 이미 저장된 값을 여기서 맞춘다.
--
-- 겨냥이 좁다: 계약완료에 서 있고 공이 시공사인 행만. 그 조합이 이 버그가 남긴 자취다.
-- 다른 칸의 '시공사' 는 맞는 값이고(행위신고~개통완료), 반려·업로드가 바꿔 둔 공 차례
-- (영업사·한백)도 건드리지 않는다.
--
-- 멱등: 두 번째 실행은 0행이다.
update projects p
set court = '한백'
where p.court = '시공사'
  and exists (
    select 1 from processes s
    where s.project_id = p.id and s.status = '계약완료'
  );
