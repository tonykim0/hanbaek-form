-- 「시공진행필요」를 「충전기 발주」로 — 발주와 수령을 두 칸으로 갈랐다 (한백 지시 2026-08-26)
--
-- 한 칸에 발주(한백)와 수령(현장)이 같이 있어서 차례를 넘길 자리가 없었다. 칸을 가르면
-- 「발주 → (차례 넘김) → 수령」이 보드에서 보인다. 칸 이름도 그 일을 말한다 —
-- 「시공진행필요」는 무엇을 해야 하는지 이름이 말해 주지 않았다.
--
-- 진행현황은 글자로 담기므로(processes.status) 옛 이름이 남으면 그 현장은 어느 칸에도
-- 속하지 못하고 첫 칸으로 떨어진다(asProcessStatus 의 안전장치). 값을 같이 옮긴다.
update processes set status = '충전기 발주' where status = '시공진행필요';
