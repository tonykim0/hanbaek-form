-- 나이스·현대엔지니어링·플러그링크의 「자체투자 (신규위치)」를 데이터에서도 없앤다 (한백 2026-08-27)
-- 정의: types/project.ts 의 normalizeRepl · replTypesOf · SPLITS_SELF_REPL
--
-- 이 세 운영사에는 제자리교체·신규위치라는 구분이 없다. 케이스는 0027 로 한 칸이 됐고,
-- 이름은 0028 로 「자체투자」가 됐고, 단가표의 축도 세우지 않게 됐다. 그런데 현장과 라인에
-- 적힌 값은 아직 신규위치로 남아 있었다 — 노션 이관이 「위치변경교체」를 그대로 옮겼기
-- 때문이다(충북 청주 율량동 현대아파트 HB-2026-145, 플러그링크 10년 3대).
--
-- 화면은 replLabel 이 「자체투자」로 적어 주니 눈에는 안 보인다. 그래서 더 나쁘다 —
-- 붙은 단가 케이스는 제자리교체인데 라인은 신규위치라, 축으로 케이스를 찾는 자리
-- (matchingRules 는 글자 완전 일치다)에서 그 라인만 후보가 0건이 된다.
--
-- 금액은 안 바뀐다. 세 운영사는 두 유형의 단가가 같아서 합친 것이고, 이미 붙은 케이스도
-- 그대로 남는다 — 바뀌는 것은 라인이 자기 케이스와 같은 축을 말하게 되는 것뿐이다.
-- 에버온·SK일렉링크는 교체유형이 실제로 단가를 갈라서 손대지 않는다.
--
-- 다시 생기지 않게 들어오는 자리도 함께 막았다: 접수 저장(pg-store)·노션 이관 스크립트가
-- normalizeRepl 을 거치고, 단가 케이스 저장은 checkPricingRule 이 그 조합을 거부한다.

update contract_lines cl
set repl_type = '자체투자 (제자리교체)'
from projects p
where p.id = cl.project_id
  and p.cpo in ('나이스인프라', '현대엔지니어링', '플러그링크')
  and cl.repl_type = '자체투자 (신규위치)';

update projects
set repl_type = '자체투자 (제자리교체)'
where cpo in ('나이스인프라', '현대엔지니어링', '플러그링크')
  and repl_type = '자체투자 (신규위치)';
