-- 정의: lib/pricing-policy-plhec-h2.ts 의 PL_INSTALL_APT · PL_INSTALL_BIZ · plInstall()
--
-- 여덟 케이스 전부에 ★같은 한 덩어리★가 붙어 있었다: 공동주택 조건을 적고 그 끝에
-- 「· 상업시설은 주차면 2%만(…)」을 곁말로 단 것이다. 그래서 상업시설 케이스를 열면
-- 「총 주차면의 5%까지 지원」과 「1개 단지 최대 130대(7년)/120대(10년)」이 먼저 보이고,
-- 정작 자기 조건은 그 뒤에 딸려 있었다 — 상업시설 조건이 제 자리에 선 적이 없다.
-- 공동주택 케이스에도 상관없는 상업시설 문구가 붙어 있었다.
--
-- 「7년 계약·한전불입 불가」는 조건 칸에서 뺀다. 그것은 이 케이스의 제약이 아니라
-- ★그 케이스가 아예 없는 이유★다(한백 확인 2026-08-29: 상업시설은 7년·한전불입 불가,
-- 연동 상업시설도 안 된다). 조건에 적어 두면 「이 케이스에 그런 제약이 있다」로 읽힌다 —
-- 대신 무엇이 되는지를 적는다: 10년 모자분리만.
--
-- 금액·축·기성은 손대지 않는다. 바뀌는 것은 설치조건 한 칸이다.
-- 케이스는 참조되면 불변이지만 이 칸은 조건 기록이라 값 계산에 들어가지 않는다 —
-- 0005·0007 이 이미 같은 방식으로 조건 칸만 갱신했다.

update pricing_rules
set install_terms =
  '총 주차면의 2%까지 지원 · 10년 모자분리만 (7년 계약·한전불입 불가)'
  || ' · 대상지: 공영주차장 · 관공서 · 주민센터 · 지식산업센터 · 4성 이상 호텔/리조트 · 사옥 · 골프장 · 병원'
where cpo = '플러그링크'
  and start_date = '2026년 하반기'
  and bldg_types::text like '%상업시설%';

update pricing_rules
set install_terms =
  '총 주차면의 5%까지 지원 · 충전기 최소 2% 전용 구역 도색 필수 · 1개 단지 최대 130대(7년)/120대(10년)'
where cpo = '플러그링크'
  and start_date = '2026년 하반기'
  and bldg_types::text not like '%상업시설%'
  and install_terms is not null;
