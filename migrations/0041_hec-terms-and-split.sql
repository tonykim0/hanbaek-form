-- 현대엔지니어링 — 설치조건 두 줄을 걷고, 하반기 분해를 시공 110만으로 맞춘다 (한백 2026-08-29)
-- 정의: lib/pricing-policy-plhec-h2.ts 의 HEC_INSTALL · HEC_PAYOUT_CONS
--
-- 설치조건에서 걷는 것:
--  · 착공 지시 후 90일 내 준공 (패널티)
--  · 모자분리만 (한전불입 불가) — 자체투자에 한전불입 케이스가 없는 것은 사실이지만 조건 칸에
--    적을 말이 아니다. 그 케이스가 없는 이유이고, 없는 케이스는 매트릭스의 빈 칸이 말한다
--
-- ★분해 — 현대엔지니어링은 기본공사비 110만 · 마진 20만, 나머지가 영업비다.★ 상반기(230만)와
-- 하반기 환경부 공동주택(250만)은 처음부터 그 분해인데 두 자리가 어긋나 있었다:
--   자체투자 180만   영업 60 + 시공 100 + 마진 20  →  영업 50 + 시공 110 + 마진 20
--   환경부 상업 250만 영업 100 + 시공 110 + 마진 40 →  영업 120 + 시공 110 + 마진 20  (2건)
-- 받는 단가(총액)는 그대로다 — 바뀌는 것은 협력사에게 내려가는 몫의 나눔이다. 세 케이스 모두
-- 아직 참조하는 라인이 없다(사용 0) — 지급이 소급되는 현장은 없다.
--
-- 적용 시작(2026년 7월 21일)은 계약서 날짜 기준이다 — 이미 그 값이라 손대지 않는다.

update pricing_rules
set install_terms = '· 주차면 5% 이하'
  || E'\n· 주용도 무관 — 상업시설·기타 부지(병원·골프장 등) 포함'
  || E'\n· 계약기간 7년 이상 (한전불입 지중인입 10년만 가능)'
where cpo = '현대엔지니어링' and start_date = '2026년 7월 21일';

-- 분해 — 총액은 지키고 시공 110 · 마진 20 으로 나눈다 (이미 그 값인 행은 그대로)
update pricing_rules
set sales_unit = (sales_unit + cons_unit + margin) - 1100000 - 200000,
    cons_unit = 1100000,
    margin = 200000
where cpo = '현대엔지니어링' and start_date = '2026년 7월 21일' and channel = '턴키'
  and (cons_unit <> 1100000 or margin <> 200000)
  and not exists (select 1 from contract_lines cl where cl.pricing_rule_id = pricing_rules.id);
