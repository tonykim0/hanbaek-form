-- 나이스 7월 1일 두 건도 기본공사비 95만으로 (한백 2026-08-29)
-- 0042 의 뒤끝이다 — 그때는 「정책이 8월 1일 접수건부터라 7월 접수는 옛 단가」로 보고 90만에
-- 남겼는데, 한백이 이 둘도 올리라고 했다. ★기본공사비는 정책이 정하는 값이 아니라 우리가
-- 정하는 값이다★ — 운영사 정책의 시행일과 우리가 시공사에 주는 단가의 시기는 따로 논다.
--
-- 받는 단가(총액 240만·220만)는 그대로다. 영업비 5만이 시공비로 옮겨간다:
--   10년  영업 130만 → 125만 · 시공 90만 → 95만
--    7년  영업 110만 → 105만 · 시공 90만 → 95만
-- 둘 다 사용 0건이라 소급해서 뒤틀릴 돈이 없다. 상반기(1월 27일)는 90만 그대로다.
--
-- 0042 와 같은 꼴로 적는다 — sales_unit 을 새로 적지 않고 cons_unit 에서 옮겨야
-- 총액이 어긋날 자리가 없다. cons_unit <> 950000 이 멱등을 만든다.

update pricing_rules
set sales_unit = sales_unit + cons_unit - 950000,
    cons_unit  = 950000
where cpo = '나이스인프라'
  and start_date = '2026년 7월 1일'
  and channel = '턴키'
  and cons_unit <> 950000;
