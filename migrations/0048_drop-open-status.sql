-- 「개통완료」 칸을 걷고 「준공」을 「준공완료」로 · 2차 지급 조건을 준공완료로 (한백 2026-08-31)
--
-- ① 개통완료 — 통신완료일·개통완료일은 「설치완료」 구간의 개통 상자가 이미 다 받는다.
--    그것을 적고 나서 「개통완료」라는 칸에 한 번 더 서는 것이 걸음만 늘렸다. 개통 상자는
--    이제 곧바로 「준공서류 접수/검토」를 열고, 개통완료가 지키던 조건(통신완료일·개통
--    완료 선언)은 그 칸의 게이트가 이어받는다 — 조건까지 걷으면 개통도 안 한 현장이
--    준공서류로 넘어간다.
--
-- ② 준공 → 준공완료 — 끝났다는 말이 분명해야 한다.
--
-- ③ ★영업비·시공비 2차 지급 조건을 개통완료에서 준공완료로 옮겼다.★ 개통은 됐어도
--    준공서류가 안 끝난 현장에 잔금이 나갈 수 있었다. 우리가 운영사에게 받는 기성도
--    준공을 보므로, 내려주는 돈과 받는 돈이 같은 사실을 보게 맞춘다.
--    조건이 되는 날짜 칸을 새로 만든다(complete_done_at) — 준공완료는 게이트 없는 사람의
--    판단이라 체크 칸을 두지 않고, 그 칸에 들어설 때 저장소가 찍는다.
--
-- ★프로덕션 영향 없음★ (확인 2026-08-31): 개통완료·준공에 서 있는 현장 0건(최고가 착공
-- 1건), open_done_at 0건, 2차 지급 기록 0건. 그래도 옮기는 SQL 을 적는 이유는 개발 DB 와
-- 앞으로의 복원본 때문이다 — asProcessStatus 는 모르는 값을 ★첫 상태(계약완료)★ 로
-- 되돌리므로, 남겨 두면 그 현장이 공정 맨 앞으로 튕긴다.

alter table processes add column if not exists complete_done_at text;

-- 개통완료에 서 있던 현장은 다음 칸으로 — 개통은 이미 끝난 자리다
update processes set status = '준공서류 접수/검토' where status = '개통완료';

update processes set status = '준공완료' where status = '준공';

/*
 * 이미 준공완료인 현장의 2차 지급 조건 날짜 — 없으면 조건이 영원히 안 찬다.
 * 언제 준공했는지 기록이 없으므로 준공서류 제출일을 쓰고, 그것도 없으면 오늘로 둔다.
 * (프로덕션에는 해당 현장이 0건이라 실제로 채워질 행은 없다.)
 */
update processes
set complete_done_at = coalesce(completion_submit_at, to_char(now() at time zone 'Asia/Seoul', 'YYYY-MM-DD'))
where status = '준공완료' and complete_done_at is null;
