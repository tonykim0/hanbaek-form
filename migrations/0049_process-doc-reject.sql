-- 공정 서류에도 반려 사유 자리를 만든다 (한백 지시 2026-08-31)
--
-- 준공서류를 칸별로 반려할 수 있게 한다. 그전에는 단계 전체에 대한 판정(「보완 필요」)만
-- 있어서, 여섯 칸 중 어느 것이 문제인지 사유 글로 풀어 써야 했다 — 받는 쪽은 그 글을
-- 읽고 다시 칸을 짚어야 했고, 그 짝짓기가 사람 몫이었다.
--
-- 계약 서류는 이미 칸마다 반려한다(documents.reject_reason). 공정 서류만 그 자리가 없어
-- 「제출 = 통과」였다. 같은 일을 두 화면이 다르게 하고 있었다.

alter table process_documents add column if not exists reject_reason text;
